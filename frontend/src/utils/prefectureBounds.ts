/**
 * 正式名称・都道府県名の省略形を判定する。
 * ひらがなやローマ字は fieldSearch.ts 側で
 * 正式名称に変換してから渡す。
 */
export function getPrefectureBounds(
  query: string
): PrefectureBounds | null {
  const normalized = query.trim()

  if (!normalized) {
    return null
  }

  const entries = Object.entries(prefectureBounds)

  const exact = entries.find(([name]) => name === normalized)

  if (exact) {
    return exact[1]
  }

  const partial = entries.find(([name]) => {
    const shortName = name.replace(/[都道府県]$/, '')

    return (
      normalized.includes(name) ||
      (shortName.length >= 2 &&
        normalized.includes(shortName))
    )
  })

  return partial?.[1] ?? null
}
